CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255),
    password VARCHAR(255),
    role VARCHAR(255)
);

CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    genre VARCHAR(255),
    description VARCHAR(5000),
    image_url VARCHAR(1000),
    igdb_id BIGINT
);

CREATE TABLE friendship (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    friend_id BIGINT,
    status VARCHAR(255),
    CONSTRAINT fk_friendship_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_friendship_friend FOREIGN KEY (friend_id) REFERENCES users (id)
);

CREATE TABLE play_invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT,
    receiver_id BIGINT,
    game_id BIGINT,
    status VARCHAR(255),
    CONSTRAINT fk_play_invites_sender FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT fk_play_invites_receiver FOREIGN KEY (receiver_id) REFERENCES users (id),
    CONSTRAINT fk_play_invites_game FOREIGN KEY (game_id) REFERENCES games (id)
);

CREATE TABLE ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    game_id BIGINT,
    type VARCHAR(255)
);

CREATE TABLE game_platforms (
    game_id BIGINT NOT NULL,
    platform VARCHAR(1000),
    CONSTRAINT fk_game_platforms_game FOREIGN KEY (game_id) REFERENCES games (id)
);
